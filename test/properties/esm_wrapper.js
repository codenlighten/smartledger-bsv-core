'use strict'
/**
 * dist/index.mjs — the real ESM entry behind the package's `import` condition.
 *
 * dist/index.js assembles its API object at run time (`const bsv = {}; bsv.PrivateKey = ...;
 * module.exports = typed`), and Node's CJS named-export detection is a STATIC scan of the
 * source, so it found nothing. `import { PrivateKey } from '@smartledger/bsv-core'` therefore
 * threw "Named export 'PrivateKey' not found" on every published version through 1.8.0 (all 16
 * carry one root export map with no `import` condition, read from the registry packument; run
 * directly against installed 1.2.0 and 1.8.0, both fail identically) — while
 * tsc ACCEPTED it, because `export = typed` over an object type permits named imports and
 * TypeScript does not model Node's lexer. Measured on published 1.8.0, Node 22.23.3, tsc 5.6.3:
 * 28 of 28 root names accepted by tsc, 0 importable by name.
 *
 * No declaration shape can report that, so the names have to exist. These checks hold the
 * wrapper to the CJS surface and prove the names are really there — a type test cannot, because
 * the failure is precisely one that type-checks.
 *
 * ESM runs in a child process rather than a dynamic import() so the source stays parseable by
 * the pinned linter.
 */

/* global describe, it, before */

require('chai').should()
const fs = require('fs')
const path = require('path')
const { execFileSync } = require('child_process')

const ROOT = path.resolve(__dirname, '../..')
const DIST = path.join(ROOT, 'dist')
const MJS = path.join(DIST, 'index.mjs')
const gen = require(path.join(ROOT, 'scripts/gen-esm-wrapper.js'))

function runEsm (body) {
  return execFileSync(process.execPath, ['--input-type=module', '-e', body],
    { cwd: ROOT, stdio: 'pipe' }).toString()
}

function fileUrl (p) { return 'file://' + p.replace(/\\/g, '/') }

describe('ESM wrapper (dist/index.mjs)', function () {
  let mod, names

  before(function () {
    fs.existsSync(MJS).should.equal(true) // `npm run build` generates it
    mod = require(path.join(DIST, 'index.js'))
    names = gen.exportableNames(mod)
  })

  it('is in sync with the CJS surface (no drift)', function () {
    fs.readFileSync(MJS, 'utf8').should.equal(gen.generate())
  })

  it('is regenerated by the build, so it cannot go stale', function () {
    const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8'))
    pkg.scripts.build.should.contain('gen-esm-wrapper.js')
    // and after tsc, or it would describe the previous build
    pkg.scripts.build.indexOf('gen-esm-wrapper.js')
      .should.be.above(pkg.scripts.build.indexOf('tsc'))
  })

  it('is what the package `import` condition resolves to', function () {
    const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8'))
    pkg.exports['.'].import.should.equal('./dist/index.mjs')
    pkg.exports['.'].require.should.equal('./dist/index.js')
    // `types` first so TypeScript resolves the declaration for both conditions.
    Object.keys(pkg.exports['.'])[0].should.equal('types')
  })

  it('covers the whole exportable CJS surface', function () {
    names.length.should.be.above(20)
    const declared = fs.readFileSync(MJS, 'utf8')
      .split('export const {')[1].split('} = mod')[0]
      .split(',').map((s) => s.trim()).filter(Boolean)
    declared.should.deep.equal(names)
  })

  // The guard proper: every name must import BY NAME and be defined.
  it('serves every member as a real ESM named export', function () {
    this.timeout(60000)
    const body = `import { ${names.join(', ')} } from "${fileUrl(MJS)}";` +
      `const u = [${names.map((n) => `["${n}", typeof ${n} === "undefined"]`).join(',')}]` +
      '.filter((p) => p[1]).map((p) => p[0]);' +
      'console.log(JSON.stringify(u))'
    JSON.parse(runEsm(body)).should.deep.equal([])
  })

  // Identity: the wrapper must not hand out copies, or `instanceof` and
  // reference comparisons would differ between an ESM and a CJS consumer.
  it('exports the same objects the CJS build does, and the same default', function () {
    this.timeout(60000)
    const body = `import mod, { PrivateKey, Transaction } from "${fileUrl(MJS)}";` +
      'import { createRequire } from "module";' +
      `const r = createRequire("${fileUrl(path.join(ROOT, 'x.js'))}");` +
      `const cjs = r("${path.join(DIST, 'index.js').replace(/\\/g, '/')}");` +
      'console.log(JSON.stringify({ def: mod === cjs, pk: PrivateKey === cjs.PrivateKey,' +
      ' tx: Transaction === cjs.Transaction }))'
    JSON.parse(runEsm(body)).should.deep.equal({ def: true, pk: true, tx: true })
  })

  it('does not re-export internal or accessor members', function () {
    names.forEach(function (n) {
      n.charAt(0).should.not.equal('_')
      const d = Object.getOwnPropertyDescriptor(mod, n)
      ;(typeof d.get).should.not.equal('function')
    })
  })

  // A named import that actually does something, so the check is not only about bindings.
  // The expected address is not this library's own output echoed back: it was taken from
  // @smartledger/bsv, an independent implementation, and agrees with core's CJS path.
  it('round-trips a key through the named ESM import', function () {
    this.timeout(60000)
    const body = `import { PrivateKey } from "${fileUrl(MJS)}";` +
      'const k = PrivateKey.fromWIF("L1uyy5qTuGrVXrmrsvHWHgVzW9kKdrp27wBC7Vs6nZDTF2BRUVwy");' +
      'console.log(k.toAddress().toString())'
    runEsm(body).trim().should.equal('17XBj6iFEsf8kzDMGQk5ghZipxX49VXuaV')
  })
})
