'use strict'

// Generates dist/index.mjs — the real ESM entry behind the package's `import` condition.
//
// dist/index.js assembles its API object at run time (`const bsv = {}; bsv.PrivateKey = ...;
// module.exports = typed`), and Node's CJS named-export detection is a STATIC scan of the
// source. It therefore finds nothing, so `import { PrivateKey } from '@smartledger/bsv-core'`
// served no binding and threw "Named export 'PrivateKey' not found" at run time — while tsc
// ACCEPTED it, because `export = typed` over an object type permits named imports and
// TypeScript does not model Node's lexer. Measured on published 1.8.0, Node 22.23.3,
// tsc 5.6.3: 28 of 28 root names accepted by tsc, 0 importable by name.
//
// No declaration can report that mismatch, so the names have to exist. This wrapper
// default-imports the CJS build (Node's ESM interop makes the default equal to
// `module.exports`, which is always reliable) and re-exports each member as a genuine named
// ESM binding. dist/index.js is left untouched, so `require()` keeps returning the very same
// object.
//
// Runs as part of `npm run build`, after tsc, and is gated by test/properties/esm_wrapper.js.
//
// One property to be aware of: `export const { X } = mod` captures each member when the wrapper
// is first evaluated, so a named export is NOT a live binding onto `module.exports`. Replacing a
// root member after load (`require('@smartledger/bsv-core').PrivateKey = Other`) is not seen by
// an already-imported named binding, though the default export holds the same object and does
// see it — that is a mutation OF the object. Reassigning `module.exports` itself would be seen
// by neither. Nothing in this package supports replacing root members, and index.mjs in the
// sibling package has always had the same property.

const fs = require('fs')
const path = require('path')

const IDENT = /^[A-Za-z_$][A-Za-z0-9_$]*$/
// Names that are reserved words / not usable as ESM export bindings.
const RESERVED = new Set([
  'default', 'import', 'export', 'const', 'let', 'var', 'function', 'class',
  'return', 'new', 'typeof', 'void', 'delete', 'in', 'instanceof', 'do', 'if',
  'else', 'switch', 'case', 'for', 'while', 'break', 'continue', 'this',
  'super', 'yield', 'await', 'enum', 'null', 'true', 'false'
])

function exportableNames (mod) {
  return Object.keys(mod)
    .filter(function (k) {
      if (!IDENT.test(k) || RESERVED.has(k)) return false
      if (k.charAt(0) === '_') return false // internal by convention
      // Skip accessor properties: destructuring them would force their side effects
      // on every ESM import. They stay reachable through the default export.
      const d = Object.getOwnPropertyDescriptor(mod, k)
      return d && typeof d.get !== 'function'
    })
    .sort()
}

function render (names) {
  return [
    '// GENERATED by scripts/gen-esm-wrapper.js during `npm run build` — do not edit.',
    '// Real ESM entry: default + named exports over the CJS build (index.js).',
    "import mod from './index.js'",
    '',
    'export default mod',
    '',
    'export const {',
    names.map(function (n) { return '  ' + n }).join(',\n'),
    '} = mod',
    ''
  ].join('\n')
}

function generate () {
  const distIndex = path.join(__dirname, '../dist/index.js')
  if (!fs.existsSync(distIndex)) {
    throw new Error('dist/index.js not found — run `tsc` before generating the ESM wrapper.')
  }
  delete require.cache[require.resolve(distIndex)]
  return render(exportableNames(require(distIndex)))
}

if (require.main === module) {
  const out = generate()
  fs.writeFileSync(path.join(__dirname, '../dist/index.mjs'), out)
  console.log('dist/index.mjs -> ' +
    exportableNames(require('../dist/index.js')).length + ' named exports')
}

module.exports = { generate, exportableNames, render }
